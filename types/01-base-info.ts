// ============================================================================
// 区块零：基础元信息 (Base Information)
// [核心价值]：物理溯源，支撑基础的数据查询与展示。
// ============================================================================
export interface BaseInfo {

    /**
     * 原文的唯一标识符或 URL Hash。
     * - 兜底追踪：确保每条资讯可精确检索、去重和关联。
     */
    id: string;

    /**
     * 资讯或文章的原始标题。
     * - 标注什么：未经加工的原始语境。
     * - 为什么用：作为前端列表展示的绝对锚点。
     * 语义：资讯或文章的原始标题。
     * 作用：最基础的展示锚点，提供未经加工的原始语境。
     */
    title: string;

    /**
     * 原始链接 URL。
     * - 为什么用：数据可追溯性的根本保障，防止大模型凭空捏造（幻觉）事件。
     */
    sourceUrl: string;

    /**
     * - 为什么用：用于构建大屏的时间轴（Timeline）和判断时效性。
     */
    publishedAt: string;

    // sourceType (信息源类型)
    // 类型：枚举 (academic_paper 学术论文 | tech_blog 技术博客/官方发布 | news_media 科技媒体/公关稿 | community_discussion 社区讨论/社交媒体)
    // 定义与语义：标识该信息的发源地生态。
    // 背后的思维维度：“信源决定信噪比”。学术论文（如 arXiv）通常代表技术前沿但缺乏商业落地；公关稿（如 TechCrunch）商业意图强但存在技术水分；社区讨论（如 Hacker News）代表了最真实的开发者情绪。这个字段能在后续分析中为内容动态分配不同的“可信度权重”。
    sourceType: 'academic_paper' | 'tech_blog' | 'news_media' | 'community_discussion';
}
